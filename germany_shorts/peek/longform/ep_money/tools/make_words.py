"""Write js/words.js: every narration word with its global start/end time (beat offset + take time).
Scenes look words up by beat + text (+ occurrence), so a re-recorded beat re-times the picture."""
import json, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from words import words
HERE = os.path.dirname(os.path.abspath(__file__)) + "/../"
OFF = json.load(open(HERE + "audio/offsets.json"))
out = {}
for b, o in OFF.items():
    if not b.startswith("b"): continue
    out[b] = [[w, round(s + o, 3), round(e + o, 3)] for w, s, e in words(b)]
js = "// generated by tools/make_words.py from the narration takes and audio/offsets.json\n"
js += "export const OFF = " + json.dumps(OFF) + ";\n"
js += "export const WORDS = " + json.dumps(out, separators=(",", ":")) + ";\n"
open(HERE + "js/words.js", "w").write(js)
print("wrote js/words.js", sum(len(v) for v in out.values()), "words; end", OFF["end"])
